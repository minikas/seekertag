function t(key) { return copy[language][key] || copy.pt[key] || key; }
function applyLanguage() {
  document.documentElement.lang = language === 'pt' ? 'pt-BR' : language;
  $('#language').value = language;
  document.querySelectorAll('[data-copy]').forEach(node => {
    const value = t(node.dataset.copy);
    if (value.includes('<span>')) node.innerHTML = value;
    else node.textContent = value;
  });
  document.querySelectorAll('[data-copy-placeholder]').forEach(node => { node.placeholder = t(node.dataset.copyPlaceholder); });
  if (currentTag) renderTag(currentTag);
  if (currentConversation) renderConversation(currentConversation);
  if (currentReward) renderReward(currentReward);
}

