$('#report-form').addEventListener('submit', async event => {
  event.preventDefault();
  const name = $('#finder-name').value.trim();
  const message = messageField.value.trim();
  $('#name-error').textContent = name.length > 60 ? t('nameTooLong') : '';
  $('#message-error').textContent = !message ? t('messageRequired') : message.length > 2000 ? t('messageTooLong') : '';
  if (!message || name.length > 60 || message.length > 2000) return;
  const button = $('#send-report');
  button.disabled = true;
  button.firstElementChild.textContent = t('sending');
  try {
    const result = await request(`/api/public/tags/${encodeURIComponent(currentTag.code)}/reports`, { method: 'POST', body: { finderName: name, message }, web: true });
    localStorage.setItem(`seekertag-chat-${currentTag.code}`, result.report.id);
    location.assign(`/chat/${encodeURIComponent(result.report.id)}`);
  } catch (error) {
    $('#message-error').textContent = friendlyError(error);
    button.disabled = false;
    button.firstElementChild.textContent = t('notifyOwner');
  }
});

function messageTime(value) {
  try { return new Intl.DateTimeFormat(language, { hour: '2-digit', minute: '2-digit' }).format(new Date(value)); }
  catch { return ''; }
}

function renderMessages(messages, report) {
  const container = $('#messages');
  const nearBottom = container.scrollHeight - container.scrollTop - container.clientHeight < 100;
  const previousLast = container.lastElementChild?.dataset.id;
  const nextLast = messages.at(-1)?.id?.toString();
  if (previousLast === nextLast && container.children.length === messages.length) return;
  container.replaceChildren(...messages.map(message => {
    const article = document.createElement('article');
    article.className = `message ${message.role === 'finder' ? 'own' : ''}`;
    article.dataset.id = message.id;
    const bubble = document.createElement('div');
    bubble.className = 'bubble';
    bubble.textContent = message.body;
    const meta = document.createElement('span');
    meta.className = 'message-meta';
    meta.textContent = `${message.role === 'finder' ? t('you') : t('owner')} · ${messageTime(message.createdAt)}`;
    article.append(bubble, meta);
    return article;
  }));
  if (nearBottom || !previousLast) requestAnimationFrame(() => { container.scrollTop = container.scrollHeight; });
}

function renderConversation(data) {
  currentConversation = data;
  const { report, tag, messages } = data;
  setItemIcon($('#chat-item-icon'), tag);
  $('#chat-item-name').textContent = tag.name || report.tagName;
  $('#chat-item-category').textContent = tag.category || '';
  $('#finder-heading').textContent = report.finderName || t('anonymous');
  setStatus($('#chat-status'), report.status, true);
  renderMessages(messages, report);
  const resolved = report.status === 'resolved';
  $('#message-form').classList.toggle('hidden', resolved);
  $('#chat-notice').classList.toggle('hidden', !resolved);
  if (resolved) {
    $('#chat-notice').classList.remove('error');
    $('#chat-notice').textContent = t('resolvedNotice');
  }
  document.title = `${t('conversation')} · ${tag.name || report.tagName} · SeekerTag`;
}

function renderReward(data) {
  currentReward = data;
  const reward = data.reward;
  const section = $('#chat-reward');
  section.classList.toggle('hidden', !reward);
  if (!reward) return;
  $('#chat-reward-label').textContent = rewardLabel(reward);
  $('#chat-reward-value').textContent = `${reward.amount} ${reward.currency}`;
  $('#chat-reward-network').textContent = networkLabel(reward.network);
  const hasWallet = Boolean(data.recipient);
  $('#wallet-saved').classList.toggle('hidden', !hasWallet);
  $('#wallet-address').textContent = data.recipient || '';
  const canSetWallet = !hasWallet && ['reserved', 'expired'].includes(reward.status) && !reward.operation && currentConversation?.report.status === 'open' && data.config;
  $('#wallet-form').classList.toggle('hidden', !canSetWallet);
}

async function loadConversation(id, { quiet = false } = {}) {
  try {
    const data = await request(`/api/finder/reports/${encodeURIComponent(id)}`);
    renderConversation(data);
    try {
      const reward = await request(`/api/finder/reports/${encodeURIComponent(id)}/reward`);
      renderReward(reward);
    } catch (error) {
      if (!quiet && error.status !== 404) {
        $('#chat-notice').textContent = friendlyError(error);
        $('#chat-notice').classList.add('error');
        $('#chat-notice').classList.remove('hidden');
      }
    }
    if (!quiet) show('chat-view');
  } catch (error) {
    if (!quiet) showError(error, true);
  }
}

async function initChat(id) {
  await loadConversation(id);
  if (!$('#chat-view').classList.contains('hidden')) {
    pollTimer = setInterval(() => { if (!document.hidden) void loadConversation(id, { quiet: true }); }, 4000);
  }
}

$('#message-form').addEventListener('submit', async event => {
  event.preventDefault();
  const field = $('#chat-message');
  const body = field.value.trim();
  if (!body) { $('#composer-error').textContent = t('messageRequired'); return; }
  const button = $('#send-message');
  button.disabled = true;
  $('#composer-error').textContent = '';
  try {
    const result = await request(`/api/finder/reports/${encodeURIComponent(currentConversation.report.id)}/messages`, { method: 'POST', body: { body } });
    currentConversation.messages.push(result.message);
    renderConversation(currentConversation);
    field.value = '';
    resizeComposer(field);
  } catch (error) { $('#composer-error').textContent = friendlyError(error); }
  finally { button.disabled = false; }
});

function resizeComposer(field) {
  field.style.height = 'auto';
  field.style.height = `${Math.min(field.scrollHeight, 130)}px`;
}
$('#chat-message').addEventListener('input', event => { $('#composer-error').textContent = ''; resizeComposer(event.target); });

