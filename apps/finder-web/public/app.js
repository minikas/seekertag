function show(view) {
  ['loading-view', 'error-view', 'found-view', 'chat-view'].forEach(id => $(`#${id}`).classList.toggle('hidden', id !== view));
}

class ApiError extends Error {
  constructor(message, status, code) { super(message); this.status = status; this.code = code; }
}

async function request(path, { method = 'GET', body, web = false } = {}) {
  let response;
  try {
    response = await fetch(path, {
      method,
      credentials: 'same-origin',
      headers: {
        Accept: 'application/json',
        ...(body === undefined ? {} : { 'Content-Type': 'application/json' }),
        ...(web ? { 'X-SeekerTag-Client': 'web' } : {}),
      },
      body: body === undefined ? undefined : JSON.stringify(body),
    });
  } catch { throw new ApiError(t('genericError'), 0, 'NETWORK_ERROR'); }
  let data;
  try { data = await response.json(); } catch { data = {}; }
  if (!response.ok) throw new ApiError(data.error || t('genericError'), response.status, data.code);
  return data;
}

function friendlyError(error) {
  if (error.code === 'UNAUTHORIZED' || error.code === 'NOT_FOUND') return error.message || t('noAccessText');
  return error.message || t('genericError');
}

function showError(error, chat = false) {
  clearInterval(pollTimer);
  $('#error-title').textContent = chat && (error.status === 401 || error.status === 404) ? t('noAccessTitle') : t('unexpectedError');
  $('#error-message').textContent = chat && (error.status === 401 || error.status === 404) ? t('noAccessText') : friendlyError(error);
  show('error-view');
}

