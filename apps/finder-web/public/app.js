function setItemIcon(node, tag) {
  node.textContent = icons[tag.categoryIcon] || icons[tag.category] || '◇';
  node.style.backgroundColor = tag.color || 'var(--accent-soft)';
}

function statusLabel(status, report = false) {
  if (report) return status === 'resolved' ? t('closed') : t('open');
  return status === 'lost' ? t('lost') : t('active');
}

function setStatus(node, status, report = false) {
  node.textContent = statusLabel(status, report);
  node.className = `status-pill ${status === 'lost' ? 'lost' : status === 'resolved' ? 'closed' : ''}`;
}

function rewardLabel(reward) {
  return t({ pending: 'rewardPending', reserved: 'rewardReserved', expired: 'rewardExpired', released: 'rewardReleased', refunded: 'rewardRefunded', unverified: 'rewardUnverified' }[reward?.status] || 'reward');
}

function networkLabel(network) {
  if (!network || network === 'mainnet') return '';
  return t(network);
}

function renderTag(tag) {
  currentTag = tag;
  setItemIcon($('#item-icon'), tag);
  $('#item-name').textContent = tag.name;
  $('#item-category').textContent = tag.category || '';
  setStatus($('#item-status'), tag.status);
  $('#owner-message-card').classList.toggle('hidden', !tag.publicMessage);
  $('#owner-message').textContent = tag.publicMessage || '';
  const reward = tag.reward;
  const hasReward = Boolean(reward || Number(tag.rewardAmount) > 0);
  $('#reward-card').classList.toggle('hidden', !hasReward);
  if (hasReward) {
    $('#reward-label').textContent = reward ? rewardLabel(reward) : t('reward');
    $('#reward-value').textContent = reward ? `${reward.amount} ${reward.currency}` : `${Number(tag.rewardAmount).toLocaleString(language)} ${tag.rewardCurrency}`;
    $('#reward-network').textContent = reward ? networkLabel(reward.network) : '';
  }
  document.title = `${tag.name} · SeekerTag`;
}

async function initFound(code) {
  try {
    const { tag } = await request(`/api/public/tags/${encodeURIComponent(code)}`);
    renderTag(tag);
    $('#open-app').href = `seekertag:///found/${encodeURIComponent(code)}?origin=${encodeURIComponent(location.origin)}`;
    const savedId = localStorage.getItem(`seekertag-chat-${code}`);
    if (savedId && /^[A-Za-z0-9_-]+$/.test(savedId)) {
      try {
        const existing = await request(`/api/finder/reports/${encodeURIComponent(savedId)}`);
        if (existing.report.tagCode === code) {
          $('#resume-chat').classList.remove('hidden');
          $('#resume-chat').onclick = () => location.assign(`/chat/${encodeURIComponent(savedId)}`);
        }
      } catch { localStorage.removeItem(`seekertag-chat-${code}`); }
    }
    show('found-view');
  } catch (error) { showError(error); }
}

